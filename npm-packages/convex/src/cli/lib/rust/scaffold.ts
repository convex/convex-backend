import path from "path";
// eslint-disable-next-line no-restricted-imports
import nodeFs from "fs";

export const RUST_TARGET = "wasm32-wasip1";
export const DEFAULT_RUST_CHANNEL = "nightly-2026-06-28";
export const MANAGED_BEGIN = "# >>> convex-managed:patch (begin)";
export const MANAGED_END = "# <<< convex-managed:patch (end)";

/** Header of `src/_generated/api.rs` (shared with the codegen). */
export const RUST_API_HEADER = `// @generated by \`npx convex dev\`. Do not edit; changes are overwritten.
//
// Typed references to your Convex functions for \`ctx.run_query\`,
// \`ctx.run_mutation\` and \`ctx.run_action\`. Include it from \`lib.rs\` with
//
//     #[path = "_generated/api.rs"]
//     pub mod api;
#![allow(
    non_upper_case_globals,
    non_snake_case,
    non_camel_case_types,
    dead_code,
    unused_imports,
    clippy::all
)]
`;

/** Placeholder `api.rs` until the first codegen fills it in. */
export const RUST_API_STUB = `${RUST_API_HEADER}
// No functions yet: this file is filled in by the next successful \`npx convex dev\`
// or \`npx convex deploy\`.
`;

export interface ScaffoldOptions {
  /** Path to the built-in `reqwest` shim crate (env CONVEX_REQWEST_PATH). */
  reqwestPath?: string | undefined;
  /** Path to the `convex_fn` crate (env CONVEX_FN_PATH). */
  convexFnPath?: string | undefined;
  /** Rust toolchain channel (env CONVEX_RUST_CHANNEL). */
  channel?: string | undefined;
}

export interface ScaffoldResult {
  created: string[];
  skipped: string[];
}

function convexFnDependency(rustDir: string, convexFnPath?: string): string {
  if (convexFnPath) {
    let p = path.resolve(convexFnPath);
    const rel = path.relative(path.resolve(rustDir), p);
    if (!path.isAbsolute(rel)) p = rel;
    return `convex_fn = { path = ${JSON.stringify(p.split(path.sep).join("/"))} }`;
  }
  return [
    "# TODO: `convex_fn` is not published yet. Until it is, set CONVEX_FN_PATH",
    "# when running `npx convex rust init`, or point this at a path/git dependency.",
    'convex_fn = "0.1"',
  ].join("\n");
}

export function scaffoldFiles(
  rustDir: string,
  opts: ScaffoldOptions = {},
): Record<string, string> {
  const channel = opts.channel ?? DEFAULT_RUST_CHANNEL;
  return {
    "Cargo.toml": `[package]
name = "convex_rust"
edition = "2021"
version = "0.1.0"
publish = false

[lib]
crate-type = ["cdylib"]

[dependencies]
${convexFnDependency(rustDir, opts.convexFnPath)}
serde = { version = "1", features = ["derive"] }
serde_json = "1"

# Keeps this crate standalone even when the project root is a Cargo workspace.
[workspace]
`,
    "src/lib.rs": `// Each module in this crate becomes a Convex module under \`rust/\`:
// \`src/example.rs\` is called as \`api.rust.example.greet\`.
pub mod example;

// Typed references to your Convex functions, generated by \`npx convex dev\`.
#[path = "_generated/api.rs"]
pub mod api;
`,
    "src/_generated/api.rs": RUST_API_STUB,
    "src/example.rs": `use convex_fn::{action, Ctx, Result};
use serde::Deserialize;

#[derive(Deserialize)]
pub struct GreetArgs {
    pub name: String,
}

/// An example action. Call it as \`api.rust.example.greet({ name: "you" })\`.
/// From here you can call your TypeScript functions with \`ctx.run_query\`,
/// \`ctx.run_mutation\` and \`ctx.run_action\`, using the typed references in \`crate::api\`.
#[action]
pub async fn greet(_ctx: &Ctx, args: GreetArgs) -> Result<String> {
    Ok(format!("Hello, {}!", args.name))
}
`,
    "rust-toolchain.toml": `[toolchain]
channel = ${JSON.stringify(channel)}
targets = ["${RUST_TARGET}"]
components = ["rustfmt", "clippy"]
`,
    ".cargo/config.toml": managedConfigToml(),
    ".gitignore": "target/\n",
  };
}

/**
 * Where the built-in reqwest shim lives: env CONVEX_REQWEST_PATH, else
 * `<convex package>/rust/convex_reqwest` (found by walking up from the CLI
 * entry point). Returns undefined when neither exists.
 */
export function resolveReqwestShimPath(
  env: Record<string, string | undefined> = process.env,
  rustDir?: string,
): string | undefined {
  if (env.CONVEX_REQWEST_PATH) return path.resolve(env.CONVEX_REQWEST_PATH);
  // Prefer the project's own `node_modules/convex`: the config can then refer
  // to it by a relative path, which is the same on every machine and in CI.
  if (rustDir) {
    let dir = path.resolve(rustDir);
    for (;;) {
      const shim = path.join(
        dir,
        "node_modules",
        "convex",
        "rust",
        "convex_reqwest",
      );
      if (nodeFs.existsSync(shim)) return shim;
      const up = path.dirname(dir);
      if (up === dir) break;
      dir = up;
    }
  }
  const entry = process.argv[1];
  if (!entry) return undefined;
  let dir: string;
  try {
    dir = path.dirname(nodeFs.realpathSync(entry));
  } catch {
    return undefined;
  }
  for (;;) {
    const pkg = path.join(dir, "package.json");
    if (nodeFs.existsSync(pkg)) {
      try {
        if (JSON.parse(nodeFs.readFileSync(pkg, "utf8")).name === "convex") {
          const shim = path.join(dir, "rust", "convex_reqwest");
          return nodeFs.existsSync(shim) ? shim : undefined;
        }
      } catch {
        // keep walking
      }
    }
    const up = path.dirname(dir);
    if (up === dir) return undefined;
    dir = up;
  }
}

/**
 * How a shim path is written to the config: relative to the rust dir when it
 * lives in a `node_modules` (portable across machines and CI), absolute for
 * anything else (e.g. a CONVEX_REQWEST_PATH override).
 */
export function displayShimPath(rustDir: string, shimPath: string): string {
  const inNodeModules = shimPath.split(path.sep).includes("node_modules");
  if (!inNodeModules) return shimPath;
  const rel = path.relative(path.resolve(rustDir), shimPath);
  return path.isAbsolute(rel) ? shimPath : rel;
}

/** The body of the CLI-managed block (without the markers). */
export function patchBlockBody(
  shimPath?: string,
  convexFnPath?: string,
  withReqwest = true,
): string {
  if (!withReqwest) {
    return "# Nothing to patch: no dependency uses reqwest. When one is added (cargo add reqwest),\n# the next `npx convex dev` fills in the built-in reqwest replacement here.\n";
  }
  if (!shimPath) {
    return "# The built-in reqwest shim was not found (set CONVEX_REQWEST_PATH);\n# crates that depend on reqwest will not be able to make requests.\n";
  }
  const toToml = (x: string) => JSON.stringify(x.split(path.sep).join("/"));
  // The shipped shim depends on the registry `convex_fn`; when the user's crate
  // uses a path dependency, patch the registry one to that same path so both
  // resolve to a single crate.
  const fnPatch = convexFnPath
    ? `convex_fn = { path = ${toToml(convexFnPath)} }\n`
    : "";
  return `[patch.crates-io]\nreqwest = { path = ${toToml(shimPath)} }\n${fnPatch}`;
}

/**
 * Absolute path of the user's `convex_fn` path dependency, read from
 * `<rustDir>/Cargo.toml`; undefined if it is not a path dependency.
 */
export function userConvexFnPath(rustDir: string): string | undefined {
  let toml: string;
  try {
    toml = nodeFs.readFileSync(path.join(rustDir, "Cargo.toml"), "utf8");
  } catch {
    return undefined;
  }
  const m = /^convex_fn\s*=\s*\{[^}\n]*\bpath\s*=\s*"([^"]+)"/m.exec(toml);
  return m ? path.resolve(rustDir, m[1]) : undefined;
}

export function managedConfigToml(
  shimPath?: string,
  convexFnPath?: string,
  withReqwest = false,
): string {
  // No \`[build] target\`: plain \`cargo test\` / \`cargo check\` run on the host.
  // The CLI passes \`--target ${RUST_TARGET}\` itself.
  return `# Managed by \`npx convex\`: edit with care, the block below is regenerated.

${MANAGED_BEGIN}
${patchBlockBody(shimPath, convexFnPath, withReqwest)}${MANAGED_END}
`;
}

/** Matches the old managed header that forced \`build.target\`. */
const LEGACY_BUILD_TARGET = new RegExp(
  '^\\[build\\]\\s*\\ntarget\\s*=\\s*"' + RUST_TARGET + '"[ \\t]*\\n(\\s*\\n)?',
  "m",
);

/**
 * Does the crate depend on reqwest (directly or transitively)? Looks at
 * \`Cargo.lock\` and the dependency tables of \`Cargo.toml\`.
 */
export function usesReqwest(rustDir: string): boolean {
  const read = (f: string) => {
    try {
      return nodeFs.readFileSync(path.join(rustDir, f), "utf8");
    } catch {
      return "";
    }
  };
  if (/^\[\[package\]\]\s*\nname\s*=\s*"reqwest"\s*$/m.test(read("Cargo.lock")))
    return true;
  return (
    /^\s*reqwest\s*=/m.test(read("Cargo.toml")) ||
    /^\s*\[[^\]]*\bdependencies\.reqwest\]/m.test(read("Cargo.toml"))
  );
}

/**
 * Rewrites the managed block of `<rustDir>/.cargo/config.toml` so it points at
 * the current shim. Leaves everything outside the markers alone. Returns true
 * if the file changed. Creates the file (when `Cargo.toml` exists) if it is
 * missing; leaves a file without markers alone.
 */
export function syncManagedPatch(
  rustDir: string,
  shimPath: string | undefined = resolveReqwestShimPath(process.env, rustDir),
  withReqwest: boolean = usesReqwest(rustDir),
): boolean {
  const shim = shimPath ? displayShimPath(rustDir, shimPath) : undefined;
  const file = path.join(rustDir, ".cargo", "config.toml");
  let cur: string;
  try {
    cur = nodeFs.readFileSync(file, "utf8");
  } catch {
    // No config yet (e.g. a hand-written crate): create the managed one.
    if (!nodeFs.existsSync(path.join(rustDir, "Cargo.toml"))) return false;
    nodeFs.mkdirSync(path.dirname(file), { recursive: true });
    nodeFs.writeFileSync(
      file,
      managedConfigToml(
        shim,
        shim ? userConvexFnPath(rustDir) : undefined,
        withReqwest,
      ),
    );
    return true;
  }
  const b = cur.indexOf(MANAGED_BEGIN);
  const e = cur.indexOf(MANAGED_END);
  if (b < 0 || e < b) return false;
  // Migrate configs written before the CLI passed \`--target\` itself.
  const head = cur.slice(0, b).replace(LEGACY_BUILD_TARGET, "");
  const next =
    head +
    MANAGED_BEGIN +
    "\n" +
    patchBlockBody(
      shim,
      shim ? userConvexFnPath(rustDir) : undefined,
      withReqwest,
    ) +
    cur.slice(e);
  if (next === cur) return false;
  nodeFs.writeFileSync(file, next);
  return true;
}

/** Writes the scaffold; never overwrites existing files. */
export function scaffoldRust(
  rustDir: string,
  opts: ScaffoldOptions = {},
): ScaffoldResult {
  const result: ScaffoldResult = { created: [], skipped: [] };
  for (const [rel, contents] of Object.entries(scaffoldFiles(rustDir, opts))) {
    const full = path.join(rustDir, rel);
    if (nodeFs.existsSync(full)) {
      result.skipped.push(rel);
      continue;
    }
    nodeFs.mkdirSync(path.dirname(full), { recursive: true });
    nodeFs.writeFileSync(full, contents, { flag: "wx" });
    result.created.push(rel);
  }
  return result;
}
